const REPORT_TO = 'steven@justdealspromotions.com';
function secret(): string {
    $f = data_root() . '/_events/.key';
    if (is_file($f)) { $k = trim((string)@file_get_contents($f)); if (strlen($k) >= 32) return $k; }
    ensure_dir(dirname($f));
    $k = bin2hex(random_bytes(24));
    @file_put_contents($f, $k, LOCK_EX); @chmod($f, 0600);
    return $k;
}
function key_ok(): bool { $k = (string)($_GET['key'] ?? ''); return $k !== '' && hash_equals(secret(), $k); }
function report_url(int $days = 7): string {
    return 'https://justdealspromotions.com/kits/_api/events.php?report=1&html=1&days=' . $days . '&key=' . secret();
